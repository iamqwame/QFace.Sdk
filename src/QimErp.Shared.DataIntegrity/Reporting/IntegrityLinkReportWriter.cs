using QimErp.Shared.DataIntegrity.Discovery;
using QimErp.Shared.DataIntegrity.Sql;

namespace QimErp.Shared.DataIntegrity.Reporting;

internal sealed record IntegrityContextReport(
    string ContextName,
    string ProviderName,
    IntegrityDiscoveryResult? Result,
    IntegritySqlBuilder? Sql);

/// <summary>Output must stay deterministic (no timestamps, ordinal ordering): generated docs are diffed in service PRs.</summary>
internal static class IntegrityLinkReportWriter
{
    public static void Write(TextWriter writer, string moduleKey, IReadOnlyList<IntegrityContextReport> contexts, bool includeSql)
    {
        writer.Write($"# Data integrity links: {moduleKey}\n\n");
        writer.Write("Generated by `--data-integrity-links` from the EF Core model (DATA-06). Regenerate instead of editing.\n\n");

        foreach (var context in contexts)
            WriteContext(writer, context, includeSql);
    }

    private static void WriteContext(TextWriter writer, IntegrityContextReport context, bool includeSql)
    {
        if (context.Result is null)
        {
            writer.Write($"## {context.ContextName}\n\n");
            writer.Write($"Skipped: provider `{context.ProviderName}` is not relational.\n\n");
            return;
        }

        var result = context.Result;
        writer.Write($"## {context.ContextName} (`{result.ContextKey}`)\n\n");

        var versionChecks = result.Scans.OfType<IntegrityVersionCheck>().ToList();
        var lowConfidence = result.With(IntegrityColumnStatus.LowConfidence).ToList();
        var unverifiable = result.Columns
            .Where(c => c.Status is IntegrityColumnStatus.Unverifiable or IntegrityColumnStatus.Unresolved)
            .ToList();

        writer.Write("| Summary | Count |\n|---|---|\n");
        writer.Write($"| Checked links | {result.CheckedLinks} |\n");
        writer.Write($"| Checks (all kinds) | {result.CheckCount} |\n");
        writer.Write($"| Local-copy version checks | {versionChecks.Count} |\n");
        writer.Write($"| Unindexed checked links (DATA-26) | {result.Unindexed} |\n");
        writer.Write($"| Low-confidence matches (not checked) | {lowConfidence.Count} |\n");
        writer.Write($"| Unverifiable or unresolved (not checked) | {unverifiable.Count} |\n");
        writer.Write($"| Ambiguous (not checked) | {result.Ambiguous} |\n");
        writer.Write($"| Excluded | {result.Columns.Count(c => c.Status == IntegrityColumnStatus.Excluded)} |\n\n");

        Section(writer, "Checked links",
            ["Column", "Path", "Target", "Rule", "Confidence", "Checks", "Index"],
            result.With(IntegrityColumnStatus.Checked).Select(c => new[]
            {
                Code(Column(c)), c.Path, c.Target ?? "", c.Rule ?? "", c.Confidence ?? "",
                string.Join("<br>", c.Link!.Checks.Select(k => Code(k.Name))), Index(c.Index)
            }));

        Section(writer, "Local-copy version checks",
            ["Table", "Column", "Check"],
            versionChecks.Select(v => new[] { Code(v.Root.Table.Display), Code(v.VersionColumn), Code(v.Checks[0].Name) }));

        Section(writer, "Unindexed checked links (DATA-26)",
            ["Column", "Target"],
            result.With(IntegrityColumnStatus.Checked).Where(c => c.Index == IndexCoverage.None)
                .Select(c => new[] { Code(Column(c)), c.Target ?? "" }));

        Section(writer, "Low-confidence matches (not checked until the owner confirms with Map)",
            ["Column", "Path", "Candidate target"],
            lowConfidence.Select(c => new[] { Code(Column(c)), c.Path, c.Target ?? "" }));

        Section(writer, "Unverifiable and unresolved",
            ["Column", "Path", "Reason"],
            unverifiable.Select(c => new[] { Code(Column(c)), c.Path, c.Reason ?? "" }));

        Section(writer, "Ambiguous",
            ["Column", "Path", "Candidates"],
            result.With(IntegrityColumnStatus.Ambiguous).Select(c => new[] { Code(Column(c)), c.Path, string.Join(", ", c.Candidates) }));

        Section(writer, "Excluded",
            ["Column", "Path", "Reason"],
            result.With(IntegrityColumnStatus.Excluded).Select(c => new[]
            {
                Code(Column(c)), c.Path, c.Target is null ? c.Reason ?? "" : $"{c.Reason} ({c.Target})"
            }));

        if (!includeSql || context.Sql is null)
            return;

        writer.Write("### SQL\n\n");
        foreach (var scan in result.Scans)
        {
            var sql = scan switch
            {
                IntegrityLink link => context.Sql.Link(link, BatchRange.None),
                IntegrityVersionCheck version => context.Sql.Unversioned(version, BatchRange.None),
                _ => throw new InvalidOperationException($"Unsupported scan type {scan.GetType().Name}.")
            };
            writer.Write($"#### `{scan.CheckPrefix}`\n\n```sql\n{sql}\n```\n\n");
        }
    }

    private static void Section(TextWriter writer, string title, string[] headers, IEnumerable<string[]> rows)
    {
        var list = rows.ToList();
        writer.Write($"### {title}\n\n");
        if (list.Count == 0)
        {
            writer.Write("None.\n\n");
            return;
        }

        writer.Write("| " + string.Join(" | ", headers) + " |\n");
        writer.Write("|" + string.Concat(headers.Select(_ => "---|")) + "\n");
        foreach (var row in list)
            writer.Write("| " + string.Join(" | ", row.Select(Escape)) + " |\n");
        writer.Write("\n");
    }

    private static string Column(IntegrityColumnReport column) => $"{column.Table.Display}.{column.Column}";

    private static string Code(string value) => $"`{value}`";

    private static string Escape(string value) => value.Replace("|", "\\|", StringComparison.Ordinal);

    private static string Index(IndexCoverage index) => index switch
    {
        IndexCoverage.Leading => "leading",
        IndexCoverage.NonLeading => "non-leading",
        _ => "none"
    };
}
